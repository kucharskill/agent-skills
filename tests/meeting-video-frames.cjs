const path=require('node:path');
const os=require('node:os');
const cp=require('node:child_process');
const assert=require('node:assert/strict');
const fixtureRoot=path.resolve(__dirname,'../.tmp/frame-tests'); fs.mkdirSync(fixtureRoot,{recursive:true});
const root=fs.mkdtempSync(path.join(fixtureRoot,'run-'));
const script=path.resolve(__dirname,'../meeting-video-frames/scripts/extract_frames.js');
const run=(cmd,args,ok=true)=>{
 const r=cp.spawnSync(cmd,args,{encoding:'utf8',windowsHide:true,timeout:180000,maxBuffer:4e6});
 if(ok)assert.equal(r.status,0,r.stderr);
 else assert.notEqual(r.status,0);
 return r;
};
const video=path.join(root,'meeting with spaces-ć.mp4');
run('ffmpeg',['-v','error','-f','lavfi','-i','color=c=red:s=320x180:r=2:d=4','-f','lavfi','-i','color=c=blue:s=320x180:r=2:d=4','-f','lavfi','-i','color=c=red:s=320x180:r=2:d=4','-filter_complex','[0:v][1:v][2:v]concat=n=3:v=1:a=0[v]','-map','[v]','-c:v','libx264','-pix_fmt','yuv420p',video]);
const original=fs.readFileSync(video);
const extract=(file=video)=>JSON.parse(run('node',[script,file]).stdout);
const result=extract();
const manifest=()=>JSON.parse(fs.readFileSync(result.manifest,'utf8'));
let m=manifest();
assert.equal(m.status,'complete');
assert.equal(m.interval_seconds,1);
assert.equal(m.frames.length,3);
assert.equal(m.skipped.length,9);
assert.deepEqual(m.frames.map(f=>f.source_seconds),[0,4,8]); assert.deepEqual(m.frames.map(f=>f.file),['frame-000000s.jpg','frame-000004s.jpg','frame-000008s.jpg']); assert.equal(JSON.parse(fs.readFileSync(result.manifest)).candidate_count,12);
assert.equal(m.source.path,fs.realpathSync(video));
assert(result.directory.startsWith(path.join(os.tmpdir(),'meeting-video-frames')));
for(const frame of m.frames){const bytes=fs.readFileSync(path.join(result.directory,frame.file));assert(bytes.length>100);assert.equal(bytes.readUInt16BE(0),0xffd8);}
assert.deepEqual(fs.readFileSync(video),original);
assert.equal(extract().cached,true);
fs.unlinkSync(path.join(result.directory,m.frames[1].file));
assert.equal(extract().cached,false);
assert.equal(manifest().frames.length,3);
fs.writeFileSync(path.join(result.directory,'.lock'),'test');
run('node',[script,video],false);
fs.unlinkSync(path.join(result.directory,'.lock'));
const other=path.join(root,'other');fs.mkdirSync(other);
const otherVideo=path.join(other,path.basename(video));fs.copyFileSync(video,otherVideo);
assert.notEqual(extract(otherVideo).directory,result.directory);
const before=fs.statSync(video);
fs.utimesSync(video,before.atime,new Date(before.mtimeMs+2000));
assert.notEqual(extract().directory,result.directory);
